export function getErrorI18nKey(code?: string): string {
  if (!code) return "errors.NETWORK_ERROR";
  if (ERROR_CODE_MAP[code]) return ERROR_CODE_MAP[code];
  if (code.endsWith("_ERROR")) return "errors.INTERNAL_ERROR";
  return "errors.UNKNOWN_ERROR";
}
